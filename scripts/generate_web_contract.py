"""Generate response-only TypeScript contracts from explicit product schemas."""

import json
import sys
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from viesett.domain.product import (
    DossierSnapshotResponse,
    PreviewResponse,
    SessionResponse,
    WebConfigResponse,
)
from viesett.domain.schemas import PolicyOut, WorkspaceOut


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    if "anyOf" in schema:
        return " | ".join(ts(v) for v in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "(" + ts(schema.get("items", {})) + ")[]"
    if kind == "object":
        if "properties" in schema:
            return (
                "{ "
                + " ".join(
                    json.dumps(k) + ": " + ts(v) + ";" for k, v in schema["properties"].items()
                )
                + " }"
            )
        return "Record<string, " + ts(schema.get("additionalProperties", {})) + ">"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }.get(str(kind), "unknown")


def main() -> None:
    definitions = {}
    models: list[type[BaseModel]] = [
        DossierSnapshotResponse,
        PreviewResponse,
        SessionResponse,
        WebConfigResponse,
        WorkspaceOut,
        PolicyOut,
    ]
    for model in models:
        schema = model.model_json_schema(mode="serialization")
        definitions.update(schema.pop("$defs", {}))
        definitions[model.__name__] = schema
    value = (
        "// Generated by scripts/generate_web_contract.py; response fields are always serialized.\n"
    )
    value += (
        "\n".join(
            "export type " + name + " = " + ts(schema) + ";"
            for name, schema in sorted(definitions.items())
        )
        + "\n"
    )
    path = Path("web/src/contracts.ts")
    if "--check" in sys.argv:
        assert path.read_text() == value, "Regenerate the product web contracts"
    else:
        path.write_text(value)


if __name__ == "__main__":
    main()
